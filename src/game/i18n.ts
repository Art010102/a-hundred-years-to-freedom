const PACKS: Record<Lang, Record<UiKey, string>> = { en, es, de, hi, ja, zh };

const ZONES: Record<string, UiKey> = {
  Showers: "zoneShowers",
  "Warden's office": "zoneOffice",
  "Mess hall": "zoneMess",
  "The yard": "zoneYard",
  "The Spine": "zoneSpine",
  "Cell block": "zoneBlock",
  Outside: "zoneOutside",
};

export function t(key: UiKey, lang: Lang = getSettings().lang, vars?: Record<string, string | number>) {
  let s = PACKS[lang][key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function zoneLabel(name: string, lang: Lang) {
  const key = ZONES[name];
  return key ? t(key, lang) : name;
}

export function verbLabel(verb: string | null, lang: Lang) {
  if (verb === "Do it") return t("doIt", lang);
  if (verb === "Talk") return t("talk", lang);
  if (verb === "Look") return t("look", lang);
  if (verb === "Hold") return t("hold", lang);
  if (verb === "Open") return t("open", lang);
  return verb ? t("act", lang) : t("act", lang);
}

export function nearLabel(near: string | null, lang: Lang) {
  if (near === "Work spot") return t("workSpot", lang);
  if (near === "Cell door") return t("cellDoor", lang);
  return near;
}
